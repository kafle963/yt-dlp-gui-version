def svg_pixmap(name: str, color: str = Tokens.TEXT_SECONDARY, size: int = 14) -> QPixmap:
    """Renders a crisp vector icon from the built-in Lucide SVG dictionary."""
    paths = _SVG_PATHS.get(name, _SVG_PATHS["play"])
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="1.8" '
        f'stroke-linecap="round" stroke-linejoin="round">{paths}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return pixmap


def svg_icon(name: str, color: str = Tokens.TEXT_SECONDARY, size: int = 14) -> QIcon:
    """Returns a QIcon rendered from crisp vector SVG."""
    return QIcon(svg_pixmap(name, color=color, size=size))
